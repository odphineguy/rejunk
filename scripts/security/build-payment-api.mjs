import { build } from "esbuild";
for (const [entry, output] of [
  ["payEntry", "pay"],
  ["webhookEntry", "stripe-webhook"],
]) {
  await build({
    entryPoints: [`server/payments/${entry}.ts`],
    outfile: `api/${output}.js`,
    bundle: true,
    platform: "node",
    format: "esm",
    packages: "external",
    banner: {
      js: "// Generated by scripts/security/build-payment-api.mjs. Do not edit.",
    },
  });
}
